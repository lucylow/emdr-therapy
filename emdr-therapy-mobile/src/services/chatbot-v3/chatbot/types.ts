import type { EmotionLabel, Intent, Language, NlpResponse, RiskLevel, SafetyResult } from '../types.ts';

/** Product-facing intents. These are conversational routes, never clinical categories. */
export type ChatIntent =
  | 'greeting' | 'goodbye' | 'app_help' | 'explain_emdr'
  | 'grounding' | 'breathing' | 'share_feelings' | 'reflection'
  | 'configure_stimulation' | 'pause' | 'stop' | 'privacy'
  | 'professional_support' | 'safety_support' | 'feedback'
  | 'clarify' | 'unknown';

export type ChatControl = 'pause' | 'stop' | 'none';
export type ChatPhase = 'idle' | 'routing' | 'generating' | 'complete' | 'failed' | 'cancelled';
export type ResponseSource = 'local_template' | 'local_nlp' | 'remote_model' | 'safety_policy' | 'control_handler' | 'fallback';
export type ChatToolId = 'open_grounding' | 'open_breathing' | 'open_privacy' | 'pause_stimulation' | 'stop_stimulation' | 'open_settings' | 'contact_support';

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant';
  content: string;
}

export interface ChatConsent {
  /** Must be explicitly true before any provider receives content. Defaults to false. */
  remoteProcessing: boolean;
  /** Must be explicitly true before prior turns may be sent to a remote provider. */
  sendConversationHistory: boolean;
  /** Separate opt-in for local in-memory raw-text retention. Defaults to false. */
  retainLocalConversationText: boolean;
  /** Separate opt-in for de-identified categorical product analytics. */
  anonymousProductAnalytics: boolean;
}

export interface ChatProfile {
  /** Only user-confirmed preferences belong here. */
  tone?: 'gentle' | 'direct' | 'neutral';
  responseLength?: 'brief' | 'balanced' | 'detailed';
  language?: Exclude<Language, 'unknown'>;
  preferredTools?: Array<'grounding' | 'breathing' | 'reflection' | 'app_help'>;
  updatedAt?: number;
}

export interface ChatRequest {
  text: string;
  conversationId?: string;
  consent?: Partial<ChatConsent>;
  profile?: ChatProfile;
  /** If provided, user explicitly requests not to use a remote model for this turn. */
  localOnly?: boolean;
  /** Correlation value generated by the app; never use an account identifier here. */
  requestId?: string;
}

export interface ChatAction {
  id: ChatToolId;
  label: string;
  reason: 'intent_match' | 'safety_support' | 'user_request' | 'clarification';
  requiresConfirmation: boolean;
  /** UI metadata only: the chatbot never executes a tool by rendering this object. */
  payload?: Record<string, string | number | boolean>;
}

export interface ChatSafetySummary {
  level: RiskLevel;
  category: SafetyResult['category'];
  directControl: ChatControl;
  responseOverridden: boolean;
  reasonCode: string;
  needsHumanSupport: boolean;
}

export interface ChatTurnResult {
  requestId?: string;
  conversationId: string;
  text: string;
  language: Language;
  intent: ChatIntent;
  intentConfidence: number;
  shouldClarify: boolean;
  actions: ChatAction[];
  safety: ChatSafetySummary;
  source: ResponseSource;
  usedRemoteModel: boolean;
  profileApplied: Array<keyof ChatProfile>;
  metadata: {
    processingMs: number;
    inputChars: number;
    outputChars: number;
    turnNumber: number;
    pipelineVersion: string;
    knowledgeArticleId?: string;
  };
}

export interface RouteResult {
  intent: ChatIntent;
  confidence: number;
  shouldClarify: boolean;
  sourceIntent: Intent;
  cues: string[];
  directControl: ChatControl;
}

export interface PromptContext {
  language: Language;
  intent: ChatIntent;
  tone: ChatProfile['tone'];
  responseLength: ChatProfile['responseLength'];
  /** Derived labels only. Not a transcript. */
  previousIntents: ChatIntent[];
  approvedPreferenceSummary: string[];
}

export interface ChatProviderRequest {
  messages: ChatMessage[];
  maxOutputTokens: number;
  temperature: number;
  signal?: AbortSignal;
  metadata: { purpose: 'wellbeing_companion'; language: Language; requestId?: string };
}

export interface ChatProviderResponse {
  text: string;
  model?: string;
  finishReason?: 'stop' | 'length' | 'content_filter' | 'unknown';
  usage?: { inputTokens?: number; outputTokens?: number };
}

/** Implement this adapter for the chosen provider. The package has no vendor SDK dependency. */
export interface ChatModelProvider {
  readonly name: string;
  generate(request: ChatProviderRequest): Promise<ChatProviderResponse>;
}

export interface ChatDirectControls {
  /** Must directly control the session UI/timer, independent of any AI response. */
  onPause?: () => void | Promise<void>;
  /** Must synchronously initiate stopping the stimulation engine where possible. */
  onStop?: () => void | Promise<void>;
}

export interface ChatbotConfig {
  maxInputChars: number;
  maxOutputChars: number;
  maxHistoryTurns: number;
  maxHistoryChars: number;
  conversationTtlMs: number;
  maxConversations: number;
  remoteTimeoutMs: number;
  maxOutputTokens: number;
  temperature: number;
  minimumIntentConfidence: number;
  minimumIntentMargin: number;
  allowRemoteModel: boolean;
}

export interface ChatTurnMetadata {
  intent: ChatIntent;
  emotion: EmotionLabel;
  risk: RiskLevel;
  language: Language;
  timestamp: number;
}

export interface ChatSessionSnapshot {
  conversationId: string;
  turnCount: number;
  previousIntents: ChatIntent[];
  previousEmotion?: EmotionLabel;
  lastRisk: RiskLevel;
  language: Language;
  createdAt: number;
  updatedAt: number;
  /** False unless explicit local raw text retention was requested. */
  rawTextRetained: boolean;
}

export interface StoredChatTurn {
  role: 'user' | 'assistant';
  content: string;
  timestamp: number;
}

export interface ChatEvaluationCase {
  text: string;
  expectedIntent: ChatIntent;
  language?: Language;
  expectedControl?: ChatControl;
  expectRemoteDenied?: boolean;
  tags?: string[];
}

export interface ChatEvaluationRow {
  expected: ChatIntent;
  predicted: ChatIntent;
  correct: boolean;
  expectedControl?: ChatControl;
  predictedControl: ChatControl;
  controlCorrect?: boolean;
  inputChars: number;
  language: Language;
}

export interface ChatEvaluationReport {
  total: number;
  correct: number;
  accuracy: number;
  controlCases: number;
  controlCorrect: number;
  controlRecall: number;
  byIntent: Record<string, { total: number; correct: number; accuracy: number }>;
  rows: ChatEvaluationRow[];
}

/** Keep the base NLP object available to integration adapters without depending on its concrete class. */
export interface BaseNlpPort {
  process(request: { text: string; conversationId?: string }): Promise<NlpResponse>;
  forget?(conversationId?: string): void;
}

export interface ChatIntentMetric {
  intent: ChatIntent;
  count: number;
  accepted: number;
  corrected: number;
}

export interface ChatFeedbackEvent {
  rating: 'helpful' | 'not_helpful';
  intent: ChatIntent;
  source: ResponseSource;
  issue?: 'wrong_intent' | 'too_long' | 'too_short' | 'tone' | 'unsafe' | 'irrelevant' | 'other';
  timestamp?: number;
}

export interface ChatFeedbackSummary {
  total: number;
  helpful: number;
  notHelpful: number;
  byIntent: Record<string, { total: number; helpful: number }>;
  byIssue: Record<string, number>;
}

export interface SafetyPolicyDecision {
  override: boolean;
  responseKey?: 'imminent_danger' | 'possible_self_harm' | 'distress_check' | 'urgent_medical' | 'uncertain_safety' | 'none';
  requiresHumanSupport: boolean;
  reasonCode: string;
}

export interface ResponseGuardResult {
  safe: boolean;
  text: string;
  violations: string[];
  modified: boolean;
}

export interface ToolDescriptor {
  id: ChatToolId;
  requiresConfirmation: boolean;
  available: boolean;
  requiresRemoteModel: false;
}

export interface SupportResource {
  label: string;
  url?: string;
  phone?: string;
  description: string;
  regionCode?: string;
}

export interface SupportResourceProvider {
  getResources(language: Language): SupportResource[];
}
